package kr.inmc.core.util

/**
 * [Text] 가 플레이스홀더 주머니에게 요구하는 **전부**.
 *
 * 각 플러그인의 `Ph` 는 토큰이 서로 다르다 — 몬스터는 `{몹}` `{수식어}` `{페이즈}`,
 * urb 는 `{박스}` `{등급}`, 숫자야구는 `{게임}` `{시도}`. 그래서 `Ph` 자체는 공통화
 * 대상이 아니었고, 그 때문에 `Text` 도 4세대에서 밖으로 나오지 못했다.
 *
 * 실제로 `Text` 가 `Ph` 에게 시키는 일은 문자열 치환 한 번뿐이다. 그것만 계약으로 뽑으면
 * 각 플러그인의 `Ph` 는 선언부에 `: Placeholders` 한 마디만 붙이면 되고, 내용은 그대로 남는다.
 */
fun interface Placeholders {

    /** 원문의 토큰을 값으로 바꿔 돌려준다. 바꿀 것이 없으면 원문 그대로. */
    fun apply(raw: String): String
}
